/**
 * Bundles the local ontouml-js library (../../src) into a single browser-safe
 * CJS file and emits it as an importable TS module. OntoumlSandpack injects it
 * into every playground as `/node_modules/ontouml-js/index.js`, so the live
 * exercises always run the exact API version the docs are written against —
 * no npm publish needed, and no fetch of the outdated `latest` release.
 *
 * Runs automatically via the website's `prestart`/`prebuild` scripts.
 */
import * as esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const websiteDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const repoRoot = path.dirname(websiteDir);
const entry = path.join(repoRoot, 'src', 'index.ts');
const outFile = path.join(
  websiteDir,
  'src',
  'components',
  'OntoumlSandpack',
  'ontouml-bundle.generated.ts'
);

// `uniqid` conditionally requires the Node built-in `os` to read a MAC
// address; in the browser sandbox an empty stub is fine (it falls back to '').
const stubNodeBuiltins = {
  name: 'stub-node-builtins',
  setup(build) {
    build.onResolve({ filter: /^os$/ }, args => ({
      path: args.path,
      namespace: 'node-builtin-stub'
    }));
    build.onLoad({ filter: /.*/, namespace: 'node-builtin-stub' }, () => ({
      contents: 'module.exports = {};',
      loader: 'js'
    }));
  }
};

const result = await esbuild.build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  platform: 'browser',
  format: 'cjs',
  target: 'es2020',
  minify: true,
  define: { 'process.env.NODE_ENV': '"production"' },
  plugins: [stubNodeBuiltins],
  logLevel: 'warning'
});

const code = result.outputFiles[0].text;

// Sandpack injects its own `process` binding into every transpiled module; a
// top-level redeclaration in the bundle would crash it (the very bug this
// setup replaces). Guard against a dependency sneaking one in.
if (/\b(?:const|let)\s+process\b/.test(code)) {
  throw new Error(
    'Bundle declares a top-level `process` identifier, which collides with ' +
      "Sandpack's injected process shim."
  );
}

const { version } = JSON.parse(
  fs.readFileSync(path.join(repoRoot, 'package.json'), 'utf8')
);

const banner =
  '// AUTO-GENERATED by scripts/bundle-ontouml.mjs — do not edit or commit.\n';
fs.writeFileSync(
  outFile,
  banner +
    `export const ontoumlVersion = ${JSON.stringify(version)};\n` +
    `export const ontoumlBundleCode: string = ${JSON.stringify(code)};\n`
);

console.log(
  `Bundled ontouml-js@${version} for Sandpack: ${(code.length / 1024).toFixed(
    0
  )} kB -> ${path.relative(websiteDir, outFile)}`
);
